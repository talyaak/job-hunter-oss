"""Infrastructure and secret settings, loaded from the repo-root ``.env``.

User-facing behaviour (target titles, locations, threshold, weights, schedule...) lives in the
database as ``UserPreferences`` - see ``app/preferences.py``. Only secrets and machine-level
options belong here.
"""

from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict

REPO_ROOT = Path(__file__).resolve().parents[2]
ENV_FILE = REPO_ROOT / ".env"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_file=str(ENV_FILE), env_file_encoding="utf-8", extra="ignore")

    database_url: str = "sqlite:///./data/job_hunter.db"

    # --- LLM (Gemini) ---
    gemini_api_key: str = ""
    # "-latest" aliases keep working when Google retires a pinned model. Pin one if you need reproducibility.
    gemini_model: str = "gemini-flash-latest"
    gemini_api_version: str = "v1beta"
    embedding_model: str = "gemini-embedding-001"
    embedding_filter_enabled: bool = False
    embedding_shadow_mode: bool = True
    embedding_similarity_threshold: float = 0.35
    embedding_retrieve_examples: int = 2
    gemma_model: str = "gemma-4-31b-it"
    gemma_filter_enabled: bool = False
    gemma_shadow_mode: bool = True
    llm_max_retries: int = 3

    # --- LinkedIn (guest scraping via JobSpy + optional li_at cookie for full descriptions) ---
    linkedin_enabled: bool = True
    linkedin_cookie_string: str = ""
    linkedin_enrich_max: int = 60  # max authenticated description fetches per run
    linkedin_enrich_delay_seconds: float = 1.5  # base delay between fetches (jitter added)

    # --- Sources ---
    indeed_results_wanted: int = 100
    ingestion_pool_size: int = 50
    ingestion_pool_count: int = 2
    ingestion_pool_dryoff_seconds: int = 45
    jobspy_hours_old: int = 72
    google_pool_pages: int = 5
    google_ats_max_pages: int = 3
    google_playwright_enabled: bool = False
    google_playwright_headless: bool = True
    serp_api_key: str = ""

    # --- Notifications ---
    ntfy_topic: str = ""
    ntfy_server: str = "https://ntfy.sh"

    # --- Scheduler fallback (the DB preference wins when set) ---
    cron_timezone: str = "UTC"
    # False on a second backend sharing this DB, or both run cron ingestion.
    ingestion_enabled: bool = True

    # --- Network / access control ---
    api_host: str = "127.0.0.1"
    api_port: int = 8000
    cors_origins: str = "http://localhost:5173,http://127.0.0.1:5173"
    # Required for anything arriving through the tunnel. Generated by `npm run setup`.
    access_token: str = ""
    # Requests from this machine (no tunnel headers) skip the token. Set false to always require it.
    local_trust: bool = True

    # --- Apply autofill overrides (otherwise parsed from the CV) ---
    apply_full_name: str = ""
    apply_email: str = ""
    apply_phone: str = ""
    apply_location: str = ""
    apply_linkedin_url: str = ""
    apply_github_url: str = ""
    apply_portfolio_url: str = ""


settings = Settings()
